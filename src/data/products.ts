export const getProductBySlug = (slug: string) => products.find((product) => product.slug === slug);

export const getRelatedProducts = (product: Product, limit = 4) =>
  products
    .filter((item) => item.slug !== product.slug && (item.category === product.category || item.audience.some((audience) => product.audience.includes(audience))))
    .slice(0, limit);
