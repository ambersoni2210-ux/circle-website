/* Resolve the main image + alt for a product from the central config. */
export function productImageFor(p: Product) {
  return productImages[p.imageKey] ?? productImages.premiumHoodie;
}
export function productGalleryFor(p: Product) {
  return [p.imageKey, ...p.relatedImageKeys].map((k) => productImages[k] ?? productImages.premiumHoodie);
}

